using FluentAssertions;
using VideoSplitJoiner.Core.Ffmpeg;
using VideoSplitJoiner.Core.Thumbnails;
using Xunit;
using Xunit.Abstractions;

namespace VideoSplitJoiner.Core.Tests;

/// <summary>
/// T-228 real-environment probe (SPEC-005 I35): real ffmpeg, killed the moment its output file appears, which is the way a latest-wins
/// hover cancels a grab. The picture the next request is served must be a whole JPEG (start and end markers present) whatever the kill
/// left behind, and no work file may stay in the cache folder. Before the fix the service wrote straight to the final name and handed
/// back whatever a killed run had left there.
/// </summary>
[Collection(MediaFixturesCollection.Name)]
public sealed class ThumbnailPartialFileIntegrationTests : IDisposable
{
    private const int Width = 640;

    private readonly MediaFixtures _fixtures;
    private readonly ITestOutputHelper _output;

    private readonly string _cacheRoot = Path.Combine(
        Path.GetTempPath(), "vsj-thumb-kill-" + Guid.NewGuid().ToString("N"));

    public ThumbnailPartialFileIntegrationTests(MediaFixtures fixtures, ITestOutputHelper output)
    {
        _fixtures = fixtures;
        _output = output;
    }

    public void Dispose()
    {
        try
        {
            if (Directory.Exists(_cacheRoot))
            {
                Directory.Delete(_cacheRoot, recursive: true);
            }
        }
        catch
        {
            // Best-effort cleanup.
        }
    }

    // SPEC-005#I35 — a run killed as soon as its output file exists (the file may be empty or short) never costs a later request a
    // whole picture, in this process or the next one, and leaves no work file. The kill can also land after ffmpeg finished: then the
    // picture is whole and the assertions hold the same.
    [Trait("serves-spec", "SPEC-005")]
    [SkippableFact]
    public async Task RealFfmpeg_AGrabKilledWhenItsFileAppears_NeverLeavesAPictureTheNextRequestServes()
    {
        FfmpegTestBinaries.Require(_output, FfmpegTestBinaries.FfmpegExists, "ffmpeg");

        var clip = _fixtures.VideoOnlyPath; // 10 s testsrc, generated by the test run
        var real = new FfmpegRunner(new FfmpegBinaryLocator(ffmpegOverride: FfmpegTestBinaries.FfmpegRequired));
        var killed = 0;
        var leftoversAfterKill = new List<string>();

        for (var second = 0; second < 9; second++)
        {
            var killer = new KillWhenOutputAppearsRunner(real);
            var cancelled = new FfmpegThumbnailService(killer, _cacheRoot);
            var during = await cancelled.GetThumbnailAsync(clip, TimeSpan.FromSeconds(second), Width, CancellationToken.None);
            if (killer.Killed && during is null)
            {
                killed++;
            }

            // The next process: no memory of the first, the same cache folder.
            leftoversAfterKill.AddRange(WorkFiles());
            var fresh = new FfmpegThumbnailService(real, _cacheRoot);
            var path = await fresh.GetThumbnailAsync(clip, TimeSpan.FromSeconds(second), Width, CancellationToken.None);

            path.Should().NotBeNull($"second {second}: a grab that was killed must not cost the next request its picture");
            IsWholeJpeg(path!).Should().BeTrue($"second {second}: the next request is served a whole picture, never what the kill left");
            JpegWidth.Read(path!).Should().Be(Width);
        }

        _output.WriteLine($"grabs killed after their output appeared and resolved to null: {killed} of 9");
        leftoversAfterKill.Should().BeEmpty("a killed grab removes its work file");
        WorkFiles().Should().BeEmpty();
    }

    // SPEC-005#I35 — the unkilled path: the picture is whole and the folder holds exactly the one final file.
    [Trait("serves-spec", "SPEC-005")]
    [SkippableFact]
    public async Task RealFfmpeg_AnUnkilledGrab_PublishesAWholePicture_AndLeavesOnlyIt()
    {
        FfmpegTestBinaries.Require(_output, FfmpegTestBinaries.FfmpegExists, "ffmpeg");

        var clip = _fixtures.VideoOnlyPath;
        var service = new FfmpegThumbnailService(
            new FfmpegRunner(new FfmpegBinaryLocator(ffmpegOverride: FfmpegTestBinaries.FfmpegRequired)), _cacheRoot);

        var hover = await service.GetThumbnailAsync(clip, TimeSpan.FromSeconds(3.7), Width, CancellationToken.None);
        var exact = await service.GetExactThumbnailAsync(clip, TimeSpan.FromSeconds(4.25), Width, CancellationToken.None);

        IsWholeJpeg(hover!).Should().BeTrue();
        IsWholeJpeg(exact!).Should().BeTrue();
        Path.GetFileName(hover).Should().Be("3000_w640.jpg");
        Path.GetFileName(exact).Should().Be("x4250000_w640.jpg");
        Directory.GetFiles(_cacheRoot, "*", SearchOption.AllDirectories).Should().HaveCount(2);
    }

    private string[] WorkFiles() =>
        Directory.Exists(_cacheRoot)
            ? Directory.GetFiles(_cacheRoot, "*.tmp.jpg", SearchOption.AllDirectories)
            : Array.Empty<string>();

    /// <summary>A JPEG that was written to its end: the start-of-image marker first, the end-of-image marker last.</summary>
    private static bool IsWholeJpeg(string path)
    {
        var bytes = File.ReadAllBytes(path);
        return bytes.Length > 4 && bytes[0] == 0xFF && bytes[1] == 0xD8 && bytes[^2] == 0xFF && bytes[^1] == 0xD9;
    }

    /// <summary>
    /// Runs the real ffmpeg and cancels it the moment its output file (the last token) exists: a kill during the write, as a hover that
    /// is superseded does. <see cref="Killed"/> says whether the cancel was sent before the run finished.
    /// </summary>
    private sealed class KillWhenOutputAppearsRunner : IFfmpegRunner
    {
        private readonly IFfmpegRunner _inner;

        public KillWhenOutputAppearsRunner(IFfmpegRunner inner) => _inner = inner;

        public bool Killed { get; private set; }

        public async Task<FfmpegResult> RunAsync(
            FfmpegArgs args,
            TimeSpan? totalDuration = null,
            IProgress<double>? progress = null,
            CancellationToken ct = default)
        {
            var output = args.ToList().Last();
            using var cts = CancellationTokenSource.CreateLinkedTokenSource(ct);
            using var watching = new CancellationTokenSource();
            var watcher = Task.Run(
                () =>
                {
                    while (!watching.IsCancellationRequested)
                    {
                        if (File.Exists(output))
                        {
                            Killed = true;
                            cts.Cancel();
                            return;
                        }

                        Thread.Yield();
                    }
                });

            try
            {
                return await _inner.RunAsync(args, totalDuration, progress, cts.Token).ConfigureAwait(false);
            }
            finally
            {
                watching.Cancel();
                await watcher.ConfigureAwait(false);
            }
        }
    }
}
